<?php

namespace PhpMake\Tests\Unit;

use PhpMake\Build\BuildValidator;
use PHPUnit\Framework\TestCase;

    /** Tests valid, invalid, and malformed build configurations. */
final class BuildValidatorTest extends TestCase
{
    /**
     * This method is called before the first test method in the test class is executed.
     *
     * @doesNotPerformAssertions
     *
     * @return void
     */
    public static function setUpBeforeClass(): void {}

    /**
     * This method is called after the last test method in the test class has been executed.
     *
     * @doesNotPerformAssertions
     *
     * @return void
     */
    public static function tearDownAfterClass(): void
    {
        gc_collect_cycles();
    }

    /**
     * This method is called BEFORE each test method.
     *
     * @doesNotPerformAssertions
     *
     * @return void
     */
    protected function setUp(): void
    {
        parent::setUp();
        // Methods initialization codes.
    }

    /**
     * This method is called AFTER each test method.
     *
     * @doesNotPerformAssertions
     *
     * @return void
     */
    protected function tearDown(): void
    {
        // Methods finalization codes.
        parent::tearDown();
    }

    /**
     * @test
     *
     * @small
     *
     * @return void
     */
    public function testValidConfig(): void
    {
        // Arrange
        $validConfig = [
            'name' => 'TestProject',
            'description' => 'Test description',
            'version' => '2.0.1',
            'targets' => [
                'clean' => [
                    'tasks' => [['type' => 'delete', 'params' => ['path' => 'test']]],
                ],
            ],
            'default_target' => 'clean',
        ];
        $validator = new BuildValidator();
        // Action
        $errors = $validator->validate($validConfig);
        // Assert
        $this->assertEmpty($errors);
    }

    /**
     * @test
     *
     * @small
     *
     * @return void
     */
    public function testMissingField(): void
    {
        // Arrange
        $invalidConfig = [
            'name' => 'TestProject',
            'targets' => [],
            'default_target' => 'clean',
        ];
        $validator = new BuildValidator();
        // Action
        $errors = $validator->validate($invalidConfig);
        // Assert
        $this->assertContains('Missing required field: description.', $errors);
    }

    /**
     * @test
     *
     * @small
     *
     * @return void
     */
    public function testInvalidTask(): void
    {
        // Arrange
        $invalidConfig = [
            'name' => 'TestProject',
            'description' => 'Test',
            'version' => '2.0.1',
            'targets' => [
                'invalid' => [
                    'tasks' => [['type' => 'unknown', 'params' => []]],
                ],
            ],
            'default_target' => 'invalid',
        ];
        $validator = new BuildValidator();
        // Action
        $errors = $validator->validate($invalidConfig);
        // Assert
        $this->assertContains("Unknown task type 'unknown' in target 'invalid'.", $errors);
    }

    /** Allows copy inputs that may be generated by an earlier build step. */
    public function testGeneratedCopySourceIsAllowedAtValidationTime(): void
    {
        // Arrange
        $config = [
            'name' => 'Test',
            'description' => 'Generated input',
            'version' => '1.0',
            'targets' => ['build' => ['tasks' => [[
                'type' => 'copy',
                'params' => ['source' => 'generated/output.bin', 'dest' => 'dist/output.bin'],
            ]]]],
            'default_target' => 'build',
        ];
        // Act
        // Assert
        $this->assertSame([], (new BuildValidator())->validate($config));
    }

    /** Reports malformed targets, task lists, and missing dependencies. */
    public function testMalformedTargetsAndDependenciesAreReported(): void
    {
        // Arrange
        $config = [
            'name' => 'Test',
            'description' => 'Malformed',
            'version' => '1.0',
            'targets' => [
                'build' => ['depends' => ['missing'], 'tasks' => 'not-an-array'],
                'bad' => 'not-an-object',
            ],
            'default_target' => 'build',
        ];
        // Act
        $errors = (new BuildValidator())->validate($config);
        // Assert
        $this->assertStringContainsString("depends on missing", implode("\n", $errors));
        $this->assertStringContainsString("valid 'tasks' array", implode("\n", $errors));
        $this->assertStringContainsString("must be an object", implode("\n", $errors));
    }

    /** Returns a validation error when targets are not an array. */
    public function testNonArrayTargetsReturnValidationError(): void
    {
        // Arrange
        $config = [
            'name' => 'Test',
            'description' => 'Bad targets',
            'version' => '1.0',
            'targets' => 'bad',
            'default_target' => 'default',
        ];
        // Act
        // Assert
        $this->assertNotEmpty((new BuildValidator())->validate($config));
    }

    /** Accepts the maximum supported exec timeout. */
    public function testExecTimeoutAtMaximumIsValid(): void
    {
        // Arrange
        $config = [
            'name' => 'Test', 'description' => 'Timeout boundary', 'version' => '1.0',
            'targets' => ['build' => ['tasks' => [[
                'type' => 'exec', 'params' => ['command' => 'php', 'timeout' => 86400],
            ]]]],
            'default_target' => 'build',
        ];
        // Assert
        // Act
        self::assertSame([], (new BuildValidator())->validate($config));
    }

    /** Rejects exec timeouts above the runtime limit. */
    public function testExecTimeoutAboveMaximumIsInvalid(): void
    {
        // Arrange
        $config = [
            'name' => 'Test', 'description' => 'Timeout boundary', 'version' => '1.0',
            'targets' => ['build' => ['tasks' => [[
                'type' => 'exec', 'params' => ['command' => 'php', 'timeout' => 86401],
            ]]]],
            'default_target' => 'build',
        ];
        // Act
        $errors = (new BuildValidator())->validate($config);
        // Assert
        self::assertStringContainsString("invalid 'timeout'", implode("\n", $errors));
    }

    /** Rejects zero and negative exec timeouts. */
    public function testNonPositiveExecTimeoutIsInvalid(): void
    {
        // Arrange
        foreach ([0, -1] as $timeout) {
            $config = [
                'name' => 'Test', 'description' => 'Timeout boundary', 'version' => '1.0',
                'targets' => ['build' => ['tasks' => [[
                    'type' => 'exec', 'params' => ['command' => 'php', 'timeout' => $timeout],
                ]]]],
                'default_target' => 'build',
            ];
        // Assert
        // Act
            self::assertStringContainsString("invalid 'timeout'", implode("\n", (new BuildValidator())->validate($config)));
        }
    }



    /** Rejects unknown properties that the JSON schema disallows. */
    public function testRejectsUnknownTaskAndTargetProperties(): void
    {
        // Arrange
        $config = [
            'name' => 'Test', 'description' => 'Test', 'version' => '1.0',
            'targets' => ['build' => [
                'unexpected' => true,
                'tasks' => [['type' => 'echo', 'params' => ['message' => 'ok'], 'extra' => true]],
            ]],
            'default_target' => 'build',
        ];

        // Act
        $errors = (new BuildValidator())->validate($config);

        // Assert
        self::assertStringContainsString("Unknown property 'unexpected'", implode("\n", $errors));
        self::assertStringContainsString("Unknown property 'extra'", implode("\n", $errors));
    }

    /** Allows an intentionally empty echo message, as the schema does. */
    public function testEmptyEchoMessageIsValid(): void
    {
        // Arrange
        $config = [
            'name' => 'Test', 'description' => 'Test', 'version' => '1.0',
            'targets' => ['build' => ['tasks' => [['type' => 'echo', 'params' => ['message' => '']]]]],
            'default_target' => 'build',
        ];

        // Act
        $errors = (new BuildValidator())->validate($config);

        // Assert
        self::assertSame([], $errors);
    }


    /** Rejects null dependencies rather than treating them as an omitted list. */
    public function testNullDependenciesAreInvalid(): void
    {
        // Arrange
        $config = [
            'name' => 'Test', 'description' => 'Null dependencies', 'version' => '1.0',
            'targets' => ['build' => ['depends' => null, 'tasks' => []]],
            'default_target' => 'build',
        ];

        // Act
        $errors = (new BuildValidator())->validate($config);

        // Assert
        self::assertStringContainsString('dependencies must be an array', implode("\n", $errors));
    }


    /** Accepts numeric JSON object keys as target names after associative decoding. */
    public function testNumericTargetNameMatchesSchema(): void
    {
        // Arrange
        $config = json_decode(
            '{"name":"NumericTarget","description":"Numeric target","version":"1.0","targets":{"1":{"tasks":[]}},"default_target":"1"}',
            true,
            512,
            JSON_THROW_ON_ERROR
        );

        // Act
        $errors = (new BuildValidator())->validate($config);

        // Assert
        self::assertSame([], $errors);
    }


}
