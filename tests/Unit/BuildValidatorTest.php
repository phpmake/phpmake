<?php

declare(strict_types=1);

namespace PhpMake\Tests\Unit;

use PhpMake\Build\BuildValidator;
use PHPUnit\Framework\TestCase;

/** Tests valid, invalid, and malformed build configurations. */
final class BuildValidatorTest extends TestCase
{
    /** Accepts a complete build configuration containing a valid task. */
    public function testValidateReturnsNoErrorsForCompleteBuildConfiguration(): void
    {
        // Arrange
        $config = [
            'name' => 'TestProject',
            'description' => 'Test description',
            'version' => '2.0.1',
            'targets' => [
                'clean' => [
                    'tasks' => [['type' => 'delete', 'params' => ['path' => 'test']]],
                ],
            ],
            'default_target' => 'clean',
        ];
        $validator = new BuildValidator();

        // Act
        $errors = $validator->validate($config);

        // Assert
        self::assertSame([], $errors);
    }

    /** Reports a missing required description field. */
    public function testValidateReportsMissingRequiredDescription(): void
    {
        // Arrange
        $config = [
            'name' => 'TestProject',
            'targets' => [],
            'default_target' => 'clean',
        ];
        $validator = new BuildValidator();

        // Act
        $errors = $validator->validate($config);

        // Assert
        self::assertContains('Missing required field: description.', $errors);
    }

    /** Reports an unknown task type with the target that contains it. */
    public function testValidateReportsUnknownTaskTypeInTarget(): void
    {
        // Arrange
        $config = [
            'name' => 'TestProject',
            'description' => 'Test',
            'version' => '2.0.1',
            'targets' => [
                'invalid' => [
                    'tasks' => [['type' => 'unknown', 'params' => []]],
                ],
            ],
            'default_target' => 'invalid',
        ];

        // Act
        $errors = (new BuildValidator())->validate($config);

        // Assert
        self::assertContains("Unknown task type 'unknown' in target 'invalid'.", $errors);
    }

    /** Allows copy inputs that may be generated by an earlier build step. */
    public function testGeneratedCopySourceIsAllowedAtValidationTime(): void
    {
        // Arrange
        $config = [
            'name' => 'Test',
            'description' => 'Generated input',
            'version' => '1.0',
            'targets' => ['build' => ['tasks' => [[
                'type' => 'copy',
                'params' => ['source' => 'generated/output.bin', 'dest' => 'dist/output.bin'],
            ]]]],
            'default_target' => 'build',
        ];

        // Act
        $errors = (new BuildValidator())->validate($config);

        // Assert
        self::assertSame([], $errors);
    }

    /** Reports malformed target entries, task lists, and missing dependencies. */
    public function testValidateReportsMalformedTargetsTasksAndDependencies(): void
    {
        // Arrange
        $config = [
            'name' => 'Test',
            'description' => 'Malformed',
            'version' => '1.0',
            'targets' => [
                'build' => ['depends' => ['missing'], 'tasks' => 'not-an-array'],
                'bad' => 'not-an-object',
            ],
            'default_target' => 'build',
        ];

        // Act
        $errors = (new BuildValidator())->validate($config);
        $messages = implode("\n", $errors);

        // Assert
        self::assertStringContainsString('depends on missing', $messages);
        self::assertStringContainsString("valid 'tasks' array", $messages);
        self::assertStringContainsString('must be an object', $messages);
    }

    /** Rejects a build configuration whose targets member is not an array. */
    public function testValidateRejectsNonArrayTargets(): void
    {
        // Arrange
        $config = [
            'name' => 'Test',
            'description' => 'Bad targets',
            'version' => '1.0',
            'targets' => 'bad',
            'default_target' => 'default',
        ];

        // Act
        $errors = (new BuildValidator())->validate($config);

        // Assert
        self::assertNotEmpty($errors);
    }

    /** Accepts an exec timeout equal to the maximum supported value. */
    public function testValidateAcceptsExecTimeoutAtMaximum(): void
    {
        // Arrange
        $config = [
            'name' => 'Test',
            'description' => 'Timeout boundary',
            'version' => '1.0',
            'targets' => ['build' => ['tasks' => [[
                'type' => 'exec',
                'params' => ['command' => 'php', 'timeout' => 86400],
            ]]]],
            'default_target' => 'build',
        ];

        // Act
        $errors = (new BuildValidator())->validate($config);

        // Assert
        self::assertSame([], $errors);
    }

    /** Rejects an exec timeout greater than the maximum supported value. */
    public function testValidateRejectsExecTimeoutAboveMaximum(): void
    {
        // Arrange
        $config = [
            'name' => 'Test',
            'description' => 'Timeout boundary',
            'version' => '1.0',
            'targets' => ['build' => ['tasks' => [[
                'type' => 'exec',
                'params' => ['command' => 'php', 'timeout' => 86401],
            ]]]],
            'default_target' => 'build',
        ];

        // Act
        $errors = (new BuildValidator())->validate($config);

        // Assert
        self::assertStringContainsString("invalid 'timeout'", implode("\n", $errors));
    }

    /** Rejects zero, negative, infinite, and non-finite exec timeout values. */
    public function testValidateRejectsNonPositiveAndNonFiniteExecTimeouts(): void
    {
        // Arrange
        $timeouts = [0, -1, INF, NAN];
        $validator = new BuildValidator();
        $errorsByTimeout = [];

        // Act
        foreach ($timeouts as $timeout) {
            $config = [
                'name' => 'Test',
                'description' => 'Timeout boundary',
                'version' => '1.0',
                'targets' => ['build' => ['tasks' => [[
                    'type' => 'exec',
                    'params' => ['command' => 'php', 'timeout' => $timeout],
                ]]]],
                'default_target' => 'build',
            ];
            $errorsByTimeout[] = $validator->validate($config);
        }

        // Assert
        foreach ($errorsByTimeout as $errors) {
            self::assertStringContainsString("invalid 'timeout'", implode("\n", $errors));
        }
    }

    /** Rejects unknown properties on targets and task entries. */
    public function testValidateRejectsUnknownTargetAndTaskProperties(): void
    {
        // Arrange
        $config = [
            'name' => 'Test',
            'description' => 'Test',
            'version' => '1.0',
            'targets' => ['build' => [
                'unexpected' => true,
                'tasks' => [['type' => 'echo', 'params' => ['message' => 'ok'], 'extra' => true]],
            ]],
            'default_target' => 'build',
        ];

        // Act
        $errors = (new BuildValidator())->validate($config);
        $messages = implode("\n", $errors);

        // Assert
        self::assertStringContainsString("Unknown property 'unexpected'", $messages);
        self::assertStringContainsString("Unknown property 'extra'", $messages);
    }

    /** Accepts an intentionally empty echo message as defined by the schema. */
    public function testValidateAcceptsEmptyEchoMessage(): void
    {
        // Arrange
        $config = [
            'name' => 'Test',
            'description' => 'Test',
            'version' => '1.0',
            'targets' => ['build' => ['tasks' => [['type' => 'echo', 'params' => ['message' => '']]]]],
            'default_target' => 'build',
        ];

        // Act
        $errors = (new BuildValidator())->validate($config);

        // Assert
        self::assertSame([], $errors);
    }

    /** Rejects null dependencies instead of treating them as an omitted list. */
    public function testValidateRejectsNullDependencies(): void
    {
        // Arrange
        $config = [
            'name' => 'Test',
            'description' => 'Null dependencies',
            'version' => '1.0',
            'targets' => ['build' => ['depends' => null, 'tasks' => []]],
            'default_target' => 'build',
        ];

        // Act
        $errors = (new BuildValidator())->validate($config);

        // Assert
        self::assertStringContainsString('dependencies must be an array', implode("\n", $errors));
    }

    /** Accepts numeric JSON object keys as target names after associative decoding. */
    public function testValidateAcceptsNumericJsonTargetNames(): void
    {
        // Arrange
        $config = json_decode(
            '{"name":"NumericTarget","description":"Numeric target","version":"1.0","targets":{"1":{"tasks":[]}},"default_target":"1"}',
            true,
            512,
            JSON_THROW_ON_ERROR
        );

        // Act
        $errors = (new BuildValidator())->validate($config);

        // Assert
        self::assertSame([], $errors);
    }

    /** Rejects task entries that omit the schema-required params property. */
    public function testValidateRejectsTaskWithoutParamsObject(): void
    {
        // Arrange
        $config = [
            'name' => 'Test',
            'description' => 'Missing params',
            'version' => '1.0',
            'targets' => ['build' => ['tasks' => [['type' => 'echo']]]],
            'default_target' => 'build',
        ];

        // Act
        $errors = (new BuildValidator())->validate($config);

        // Assert
        self::assertStringContainsString("has no valid 'params' object", implode("\n", $errors));
    }

    /** Rejects malformed metadata, target names, task entries, types, and exec arguments. */
    public function testValidateRejectsMalformedPropertiesAndTaskEntries(): void
    {
        // Arrange
        $config = [
            'name' => 'Test',
            'description' => 'Malformed metadata',
            'version' => '1.0',
            'unexpected' => true,
            'targets' => [
                '' => ['description' => 123, 'tasks' => ['not-an-object']],
                'build' => ['tasks' => [
                    ['params' => []],
                    ['type' => 'exec', 'params' => ['command' => 'php', 'args' => [new \stdClass()]]],
                ]],
            ],
            'default_target' => 'build',
        ];

        // Act
        $errors = (new BuildValidator())->validate($config);
        $messages = implode("\n", $errors);

        // Assert
        self::assertStringContainsString('Unknown top-level property', $messages);
        self::assertStringContainsString('Target names must be non-empty strings', $messages);
        self::assertStringContainsString('description must be a string', $messages);
        self::assertStringContainsString('must be an object', $messages);
        self::assertStringContainsString("has no valid 'type'", $messages);
        self::assertStringContainsString("invalid 'args'", $messages);
    }
}
